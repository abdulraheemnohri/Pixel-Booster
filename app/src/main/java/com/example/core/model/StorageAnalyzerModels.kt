package com.example.core.model

import java.util.Locale

enum class StorageVolumeType(val label: String, val description: String) {
    INTERNAL("Internal Storage", "Device core partition (/data)"),
    EXTERNAL("Shared Storage", "Media & external storage (/sdcard)"),
    APP_SANDBOX("App Sandbox", "Installed app package caches & scratchpad")
}

data class StorageVolumeInfo(
    val volumeType: StorageVolumeType,
    val path: String,
    val totalBytes: Long,
    val availableBytes: Long,
    val usedBytes: Long,
    val isRemovable: Boolean = false,
    val fileSystem: String = "ext4/f2fs"
) {
    val usedPercentage: Float
        get() = if (totalBytes > 0) ((usedBytes.toFloat() / totalBytes.toFloat()) * 100f).coerceIn(0f, 100f) else 0f

    val formattedTotal: String
        get() = MemoryInfoData.formatBytes(totalBytes)

    val formattedUsed: String
        get() = MemoryInfoData.formatBytes(usedBytes)

    val formattedAvailable: String
        get() = MemoryInfoData.formatBytes(availableBytes)
}

enum class JunkCategoryType(val title: String, val subtitle: String, val description: String) {
    APP_CACHE("Application Cache", "Temporary runtime files", "Cached data generated by user applications and browsers."),
    LARGE_FILES("Large Files (>25MB)", "Downloads & media files", "Downloaded files, media buffers, and archives occupying local disk space."),
    TEMP_FILES("Temporary Buffers", "System scratch space", "Log files, thumbnail caches, and leftover bits."),
    REDUNDANT_APKS("Redundant APKs", "Downloaded package installers", "Android package installer files (.apk) located in storage.")
}

data class JunkCategoryItem(
    val id: String,
    val category: JunkCategoryType,
    val name: String,
    val sizeBytes: Long,
    val filePath: String,
    val isSelected: Boolean = true
) {
    val formattedSize: String
        get() = MemoryInfoData.formatBytes(sizeBytes)
}

data class StorageAnalyzerReport(
    val totalJunkBytes: Long,
    val cacheBytes: Long,
    val largeFilesBytes: Long,
    val tempFilesBytes: Long,
    val redundantApksBytes: Long,
    val items: List<JunkCategoryItem>,
    val activeVolume: StorageVolumeInfo,
    val availableVolumes: List<StorageVolumeInfo>
) {
    val formattedTotalJunk: String
        get() = MemoryInfoData.formatBytes(totalJunkBytes)

    val formattedCache: String
        get() = MemoryInfoData.formatBytes(cacheBytes)

    val formattedLargeFiles: String
        get() = MemoryInfoData.formatBytes(largeFilesBytes)

    val formattedTempFiles: String
        get() = MemoryInfoData.formatBytes(tempFilesBytes)

    val formattedRedundantApks: String
        get() = MemoryInfoData.formatBytes(redundantApksBytes)
}
